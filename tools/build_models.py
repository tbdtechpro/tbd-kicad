"""Build simple 3D models (STEP + coloured VRML) with FreeCAD for parts that have no vendor model, and a
coloured VRML of the Teensy 4.1 STEP.  Run headless:
    freecad.cmd tools/build_models.py        (snap FreeCAD cannot read /tmp; keep the checkout under $HOME)
Model frames match the footprints: origin at the footprint origin, Z up from the carrier surface,
3D +Y = footprint -Y (KiCad convention).  VRML units are 0.1 inch (KiCad convention)."""
import os, math
import FreeCAD, Part

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = ROOT + '/lib/3d'

GREEN = (0.05, 0.32, 0.14); BLUE = (0.05, 0.20, 0.45); BLACK = (0.12, 0.12, 0.12); DARK = (0.08, 0.08, 0.1)
GOLD = (0.85, 0.70, 0.25); SILVER = (0.78, 0.78, 0.80); GREY = (0.35, 0.35, 0.37); WHITE = (0.9, 0.9, 0.88)


def box(x0, x1, y0, y1, z0, z1):
    return Part.makeBox(x1 - x0, y1 - y0, z1 - z0, FreeCAD.Vector(x0, y0, z0))


def cyl(r, h, base, axis=(0, 0, 1)):
    return Part.makeCylinder(r, h, FreeCAD.Vector(*base), FreeCAD.Vector(*axis))


def write_vrml(path, groups, scale=1 / 2.54):
    """groups: list of (shape, (r,g,b)) ; shapes tessellated per group."""
    out = ['#VRML V2.0 utf8', '# generated by tools/build_models.py']
    for shape, col in groups:
        verts, tris = shape.tessellate(0.08)
        if not tris:
            continue
        out.append('Shape { appearance Appearance { material Material { diffuseColor %.3f %.3f %.3f specularColor 0.2 0.2 0.2 shininess 0.3 } }'
                   % col)
        out.append(' geometry IndexedFaceSet { solid FALSE coord Coordinate { point [')
        out.append(','.join('%.4f %.4f %.4f' % (v.x * scale, v.y * scale, v.z * scale) for v in verts))
        out.append('] } coordIndex [')
        out.append(','.join('%d,%d,%d,-1' % t for t in tris))
        out.append('] } }')
    open(path, 'w').write('\n'.join(out) + '\n')


def write_step(path, groups):
    Part.makeCompound([g[0] for g in groups]).exportStep(path)


def pin_header_vertical(n, pitch=2.54, x0=None, y=0.0, z_board=2.54, below=6.0, above=1.5):
    """Male header with plastic under a board whose bottom is at z_board. Returns [(shape,colour)]."""
    x0 = -(n - 1) * pitch / 2 if x0 is None else x0
    plastic = box(x0 - pitch / 2, x0 + (n - 0.5) * pitch, y - pitch / 2, y + pitch / 2, z_board - 2.54, z_board)
    pins = [box(x0 + i * pitch - 0.32, x0 + i * pitch + 0.32, y - 0.32, y + 0.32, -below, z_board + above) for i in range(n)]
    return [(plastic, BLACK)] + [(p, GOLD) for p in pins]


def pin_header_right_angle(n, pitch=2.54, z_bend=5.0, y_board=3.4, below=3.0):
    """Right-angle header for a module standing at Y in [y_board, y_board+1.6]: vertical run at Y=0 from -below up
    to z_bend, then horizontal through the module board. Plastic sits against the board's back face."""
    x0 = -(n - 1) * pitch / 2
    groups = [(box(x0 - pitch / 2, x0 + (n - 0.5) * pitch, y_board - 2.54, y_board, z_bend - 1.27, z_bend + 1.27), BLACK)]
    for i in range(n):
        x = x0 + i * pitch
        groups.append((box(x - 0.32, x + 0.32, -0.32, 0.32, -below, z_bend + 0.32), GOLD))
        groups.append((box(x - 0.32, x + 0.32, -0.32, y_board + 1.6 + 1.0, z_bend - 0.32, z_bend + 0.32), GOLD))
    return groups


# ---------------------------------------------------------------- KY-040
def ky040():
    yb = 3.4                      # module board back face (3D Y), matches the footprint fab drawing
    g = pin_header_right_angle(5, y_board=yb)
    g.append((box(-9.5, 9.5, yb, yb + 1.6, 0.5, 26.5), BLACK))                       # PCB 19 x 26, black like the photo
    yf = yb + 1.6
    g.append((box(-6.2, 6.2, yf, yf + 6.5, 14.0 - 6.7, 14.0 + 6.7), SILVER))        # EC11 metal body 12.4 x 13.4 x 6.5
    g.append((cyl(3.5, 5.0, (0, yf + 6.5, 14.0), (0, 1, 0)), SILVER))               # threaded bushing M7 x 5
    g.append((cyl(3.0, 15.0, (0, yf + 11.5, 14.0), (0, 1, 0)), GREY))               # 6 mm shaft, 15 long
    g.append((cyl(1.1, 1.6, (0, yb, 24.0), (0, 1, 0)), WHITE))                       # mounting hole marker
    for i, x in enumerate((-6.5, -3.5, -0.5)):
        g.append((box(x, x + 1.6, yf, yf + 0.6, 7.0, 7.8), DARK))                    # 0603 pull-up resistors
    return g


# ---------------------------------------------------------------- GC9A01 round module, 7-pin header, lying flat
def gc9a01():
    zb = 2.54                     # board bottom sits on the header plastic
    R, t = 18.75, 1.2
    pcb = cyl(R, t, (0, 0, zb)).fuse(box(-13.5, 13.5, 13.01, 26.25, zb, zb + t))
    for x in (-11.5, 11.5):
        pcb = pcb.cut(cyl(1.1, 5, (x, 23.75, zb - 1)))
    g = pin_header_vertical(7, y=23.75, z_board=zb)
    g.append((pcb, BLUE))
    g.append((cyl(17.4, 1.5, (0, 0, zb + t)), BLACK))                                 # glass with black border
    g.append((cyl(16.2, 0.1, (0, 0, zb + t + 1.5)), DARK))                            # 32.4 mm active area
    g.append((box(-9, 9, 12.0, 23.0, zb + t, zb + t + 0.3), GOLD))                    # FPC tail on the tab
    return g


# ---------------------------------------------------------------- Teensy 4.1: colour the XenGi STEP by face height
def teensy():
    s = Part.Shape(); s.read(ROOT + '/lib/3d/Teensy_4.1_Assembly.step')
    solids = sorted(s.Solids, key=lambda x: -x.Volume)
    groups = {'pcb': [], 'chips': [], 'metal': []}
    for f in solids[0].Faces:
        b = f.BoundBox
        if b.ZMax <= 1.65 and b.ZMin >= -0.05:
            groups['pcb'].append(f)
        elif b.XMin < -24.0:
            groups['metal'].append(f)        # micro-USB shell at the USB end
        else:
            groups['chips'].append(f)
    for so in solids[1:]:
        groups['metal'].extend(so.Faces)     # micro SD holder
    out = []
    for key, col in (('pcb', GREEN), ('chips', BLACK), ('metal', SILVER)):
        if groups[key]:
            out.append((Part.makeShell(groups[key]) if False else Part.makeCompound(groups[key]), col))
    return out


for name, builder, step in (('KY-040_Module', ky040, True), ('GC9A01_Round_1.28in_7pin', gc9a01, True),
                            ('Teensy_4.1_Assembly', teensy, False)):
    g = builder()
    write_vrml(os.path.join(OUT, name + '.wrl'), g)
    if step:
        write_step(os.path.join(OUT, name + '.step'), g)
    print('built', name, len(g), 'groups')
