def din5(g, cx, cy, z, facing_deg):
    """PCB-mount DIN-5 socket, 20 x 19.5 x 16.5; built with the opening toward -Y, then turned by facing_deg."""
    parts = [(box(-10.0, 10.0, -9.75, 9.75, 0, 16.5), DARK), (box(-9.0, 9.0, -9.9, -9.75, 1.0, 16.0), BLACK)]
    parts.append((moved(rotx(ring(0, 0, 0, 1.2, 7.6, 6.6), -90), 0, -10.95, 8.3), SILVER))       # chrome collar
    disc = cyl(6.6, 1.0, (0, -10.9, 8.3), (0, 1, 0))
    for a in (0, 45, 90, 135, 180):
        ax, az = 3.5 * math.cos(math.radians(a)), 3.5 * math.sin(math.radians(a))
        disc = disc.cut(cyl(0.9, 3, (ax, -11.5, 8.3 + az), (0, 1, 0)))
    disc = disc.cut(box(-1.2, 1.2, -11.5, -9.5, 8.3 - 6.6, 8.3 - 4.8))                         # key notch
    parts.append((disc, BLACK))
    for s, c in parts:
        g.append((moved(rotz(s, facing_deg), cx, cy, z), c))


