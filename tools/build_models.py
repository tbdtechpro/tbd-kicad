# ---------------------------------------------------------------- Teensy 4.1: colour the XenGi STEP by face height
def teensy():
    s = Part.Shape(); s.read(ROOT + '/lib/3d/Teensy_4.1_Assembly.step')
    solids = sorted(s.Solids, key=lambda x: -x.Volume)
    groups = {'pcb': [], 'chips': [], 'metal': []}
    for f in solids[0].Faces:
        b = f.BoundBox
        if b.ZMax <= 1.65 and b.ZMin >= -0.05:
            groups['pcb'].append(f)
        elif b.XMin < -24.0:
            groups['metal'].append(f)        # micro-USB shell at the USB end
        else:
            groups['chips'].append(f)
    for so in solids[1:]:
        groups['metal'].extend(so.Faces)     # micro SD holder
    out = []
    for key, col in (('pcb', GREEN), ('chips', BLACK), ('metal', SILVER)):
        if groups[key]:
            out.append((Part.makeCompound(groups[key]), col))
    return out


