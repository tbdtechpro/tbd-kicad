    rows = n // 2
    parts = [(box(-rows * 1.27, rows * 1.27, -3.2, 3.2, 1.0, 4.3), DARK), (cyl(0.6, 0.2, (-rows * 1.27 + 0.05, 0, 4.3)), GREY)]
